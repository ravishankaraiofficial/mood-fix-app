/**
 * Translates UI elements marked with data-i18n-key
 */
export function translateUI(langCode: string) {
  // Fallback to English if language is not explicitly defined in our dict yet
  const dictionary = translations[langCode] || translations['en'];
  
  const elements = document.querySelectorAll('[data-i18n-key]');
  elements.forEach(el => {
    const key = el.getAttribute('data-i18n-key');
    if (key && dictionary[key]) {
      el.textContent = dictionary[key];
    }
  });

  // Also update document title if present
  if (dictionary.app_title) {
    document.title = dictionary.app_title;
  }
}
